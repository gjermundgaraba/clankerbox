import { writeFileSync } from "node:fs";

import { applied } from "../../../../apps/server/src/chart.ts";
import {
  desiredOf,
  leaves,
  machineChart,
  metaOf,
  stageOf,
  wants,
} from "../../../../apps/server/src/machine-chart.ts";
import type {
  Leaf,
  MachineEvent,
  MachineRow,
  Stage,
  Wish,
} from "../../../../apps/server/src/machine-chart.ts";
import type {
  MachinePhase,
  Operation,
} from "../../../../apps/server/src/store.ts";
import {
  facts,
  failure,
  flight,
  freshBoot,
  when,
} from "../../../../apps/server/tests/chart-rows.ts";

const wishes: readonly Wish[] = ["running", "stopped", "paused"];

const kinds = [
  "make",
  "start",
  "stop",
  "pause",
  "remove",
] as const satisfies ReadonlyArray<Operation["kind"]>;

const error = failure;

const resting = [
  "settled",
  "failed",
  "lost",
] as const satisfies readonly MachinePhase[];

const failedCreate = ["undoing", "undone"] as const satisfies readonly Stage[];

const undone = "undone" satisfies Leaf;

const failedLeaves = leaves.filter((leaf) =>
  failedCreate.some((stage) => stage === stageOf(leaf))
);

const events: ReadonlyArray<readonly [string, MachineEvent]> = [
  ["ask:running", { type: "ask", desired: "running" }],
  ["ask:stopped", { type: "ask", desired: "stopped" }],
  ["ask:paused", { type: "ask", desired: "paused" }],
  ["delete", { type: "delete" }],
  ...(["running", "stopped", "paused", "missing", "unknown"] as const).map(
    (seen) =>
      [
        `read:${seen}`,
        {
          type: "read",
          seen,
          boot: freshBoot(""),
          pin: undefined,
          id: "",
          joins: false,
          awaiting: false,
        },
      ] as const
  ),
  [
    "reported:done",
    { type: "reported", status: "done", outcome: {}, at: when },
  ],
  [
    "reported:failed",
    { type: "reported", status: "failed", outcome: {}, error },
  ],
  [
    "reported:cancelled",
    { type: "reported", status: "cancelled", outcome: {}, error },
  ],
  ["lost", { type: "lost", error }],
];

const string = (text: string) => `"${text}"`;

const bool = (value: boolean) => (value ? "TRUE" : "FALSE");

const flag = (value: boolean) => (value ? "1" : "0");

const entry = (
  state: Leaf,
  wish: Wish,
  prepared: boolean,
  failed: boolean,
  name: string,
  event: MachineEvent
): string | undefined => {
  const row: MachineRow = {
    ...facts({ desired: wish, prepared, error: failed ? error : undefined }),
    state,
  };

  const op = metaOf(state).step === undefined ? undefined : flight("stop");
  const { next } = applied(machineChart, row, event, op);

  const from = [state, desiredOf(row), prepared, failed] as const;

  const to =
    next === "removed"
      ? (["gone", "deleted", prepared, failed] as const)
      : ([
          next.state,
          desiredOf(next),
          next.prepared,
          next.error !== undefined,
        ] as const);

  if (to.every((value, at) => value === from[at])) {
    return undefined;
  }

  const key = `${from[0]}|${from[1]}|${flag(prepared)}|${flag(failed)}|${name}`;

  return `E(${string(key)}, ${string(to[0])}, ${string(to[1])}, ${bool(to[2])}, ${bool(to[3])})`;
};

const entries = (): readonly string[] =>
  leaves.flatMap((state) =>
    (state.startsWith("deleting.") ? (["running"] as const) : wishes).flatMap(
      (wish) =>
        [false, true].flatMap((prepared) =>
          [false, true].flatMap((failed) =>
            events.flatMap(([name, event]) => {
              const written = entry(
                state,
                wish,
                prepared,
                failed,
                name,
                event
              );

              return written === undefined ? [] : [written];
            })
          )
        )
    )
  );

const set = (values: readonly string[]) => `{${values.map(string).join(", ")}}`;

const table = (rows: ReadonlyArray<readonly [string, string]>) =>
  rows.map(([key, value]) => `${string(key)} :> ${value}`).join(" @@\n  ");

const wanted = (kind: Operation["kind"]) =>
  set(
    [...wishes, "deleted" as const].filter((desired) => wants(kind, desired))
  );

/** `Chart.tla`: every write of the real chart that changes a row, over what the model holds of one. */
export const chartModule = (): string => `---------------------------- MODULE Chart ----------------------------
(* Generated by scripts/export-chart.ts from apps/server/src/machine-chart.ts. *)
(* Don't edit it: machine-chart.test.ts fails when it is stale.                *)
EXTENDS TLC

E(k, state, desired, prepared, err) ==
  [k |-> k, v |-> [state |-> state, desired |-> desired, prepared |-> prepared,
                   err |-> err]]

(* state|desired|prepared|err|event, for each write that changes the row *)
Entries == {
  ${entries().join(",\n  ")}
}

Keys == {e.k : e \\in Entries}

Table == [k \\in Keys |-> (CHOOSE e \\in Entries : e.k = k).v]

PhaseOf ==
  ${table(leaves.map((leaf) => [leaf, string(metaOf(leaf).phase)]))}

StepOf ==
  ${table(leaves.map((leaf) => [leaf, string(metaOf(leaf).step ?? "none")]))}

Wanted ==
  ${table(kinds.map((kind) => [kind, wanted(kind)]))}

(* The phases a client's wait ends on, but waiting, which only a read shows *)
Resting == ${set(resting)}

(* The leaves of a create that failed, where only a delete finds a machine *)
FailedCreate == ${set(failedLeaves)}

Undone == ${string(undone)}
=============================================================================
`;

if (import.meta.main) {
  const [out = new URL("../model/Chart.tla", import.meta.url)] =
    process.argv.slice(2);

  writeFileSync(out, chartModule());
}

